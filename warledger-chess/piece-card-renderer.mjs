export function computeCardTargets(card) {
  const origin = squareToBoardPoint(card.originSquare);
  const targets = {};

  for (const pattern of card.movement) {
    if (pattern.kind === "rider") {
      targets[patternName(pattern)] = computeRiderTargets(origin, pattern.directions);
    }
    if (pattern.kind === "leaper") {
      targets[patternName(pattern)] = computeLeaperTargets(origin, pattern.deltas);
    }
  }

  return targets;
}

function renderHeader(card) {
  return `<g font-family="Aptos, Segoe UI, Arial, sans-serif">
    <text x="92" y="126" font-size="76" font-weight="900" letter-spacing="0" fill="#f4ecd7">${escapeXml(card.title)}</text>
    <text x="94" y="176" font-size="34" font-weight="800" fill="#d5c7a1">${escapeXml(card.subtitle)}</text>
    <g transform="translate(940 84)">
      <rect x="0" y="0" width="150" height="118" rx="18" fill="#f4ecd7" stroke="${GOLD}" stroke-width="5"/>
      <text x="75" y="72" text-anchor="middle" font-size="62" font-weight="900" fill="${INK}">${escapeXml(card.id)}</text>
      <text x="75" y="100" text-anchor="middle" font-size="18" font-weight="800" fill="${GOLD}">PIECE ID</text>
    </g>
  </g>`;
}

function renderBoard(card, computed) {
  const square = CARD.boardSize / 8;
  const origin = squareCenter(card.originSquare);
  const patterns = card.movement.map((pattern) => ({
    ...pattern,
    key: patternName(pattern),
    targets: computed[patternName(pattern)] || []
  }));
  const targetMap = new Map();

  for (const pattern of patterns) {
    for (const target of pattern.targets) {
      if (!targetMap.has(target)) {
        targetMap.set(target, []);
      }
      targetMap.get(target).push(pattern);
    }
  }

  const squares = [];
  for (let rank = 8; rank >= 1; rank -= 1) {
    for (let file = 0; file < 8; file += 1) {
      const x = CARD.boardX + file * square;
      const y = CARD.boardY + (8 - rank) * square;
      const dark = (file + (8 - rank)) % 2 === 1;
      const name = `${BOARD_FILES[file]}${rank}`;
      const squarePatterns = targetMap.get(name) || [];
      squares.push(`<rect x="${x}" y="${y}" width="${square}" height="${square}" fill="${dark ? DARK : LIGHT}"/>`);
      for (const [index, pattern] of squarePatterns.entries()) {
        const inset = 8 + index * 7;
        const opacity = pattern.kind === "rider" ? 0.22 : 0.18;
        squares.push(`<rect x="${x + inset}" y="${y + inset}" width="${square - inset * 2}" height="${square - inset * 2}" rx="12" fill="${pattern.color}" opacity="${opacity}"/>`);
      }
      squares.push(`<text x="${x + 12}" y="${y + 26}" font-size="20" font-weight="900" fill="${dark ? "#f8f3e4" : "#31404a"}" opacity="0.58">${name}</text>`);
    }
  }

  const rays = patterns
    .filter((pattern) => pattern.kind === "rider")
    .flatMap((pattern) => computeRayEnds(card.originSquare, pattern.directions).map((target) => {
      const to = squareCenter(target);
      return `<line x1="${origin.x}" y1="${origin.y}" x2="${to.x}" y2="${to.y}" stroke="${pattern.color}" stroke-width="13" stroke-linecap="round" opacity="0.48" marker-end="url(#rookArrow)"/>`;
    }))
    .join("");

  const leaperDots = patterns
    .filter((pattern) => pattern.kind === "leaper")
    .flatMap((pattern) => pattern.targets.map((target) => {
      const to = squareCenter(target);
      return `<g>
        <circle cx="${to.x}" cy="${to.y}" r="32" fill="${pattern.color}" opacity="0.92"/>
        <text x="${to.x}" y="${to.y + 9}" text-anchor="middle" font-family="Aptos, Segoe UI, Arial, sans-serif" font-size="24" font-weight="900" fill="#ffffff">${escapeXml(pattern.dotLabel || card.id)}</text>
      </g>`;
    }))
    .join("");

  return `<g>
    <rect x="${CARD.boardX - 18}" y="${CARD.boardY - 18}" width="${CARD.boardSize + 36}" height="${CARD.boardSize + 36}" rx="18" fill="#20272c"/>
    <g>${squares.join("")}</g>
    <g>${rays}</g>
    <g>${leaperDots}</g>
    <g>
      <rect x="${origin.x - 48}" y="${origin.y - 48}" width="96" height="96" rx="18" fill="${INK}" stroke="${GOLD}" stroke-width="7"/>
      <text x="${origin.x}" y="${origin.y + 18}" text-anchor="middle" font-family="Aptos, Segoe UI, Arial, sans-serif" font-size="64" font-weight="900" fill="#f4ecd7">${escapeXml(card.id)}</text>
    </g>
    ${renderLegend(patterns)}
  </g>`;
}

function renderMetadata(card, computed) {
  const rowY = 1218;
  const panelWidth = 496;
  const panelHeight = 178;
  const gap = 24;
  const panels = [
    renderInfoPanel(92, rowY, panelWidth, panelHeight, "IDENTIFIER", card.identity.map(([key, value]) => `${key}: ${value}`)),
    renderInfoPanel(92 + panelWidth + gap, rowY, panelWidth, panelHeight, "NAMES", card.names),
    renderInfoPanel(92, rowY + panelHeight + gap, panelWidth, panelHeight, "HISTORY", card.history),
    renderInfoPanel(92 + panelWidth + gap, rowY + panelHeight + gap, panelWidth, panelHeight, "NAME OVERLOAD", card.overload)
  ];
  const targetRows = card.movement.map((pattern, index) => {
    const key = patternName(pattern);
    const label = pattern.targetLabel || key;
    const targets = (computed[key] || []).join(" ");
    const y = 1150 + index * 32;
    const labelX = 122;
    const targetsX = label.length > 6 ? 252 : 214;
    return `<text x="${labelX}" y="${y}" font-size="25" font-weight="900" fill="${pattern.color}">${escapeXml(label)}</text>
    <text x="${targetsX}" y="${y}" font-size="24" font-weight="850" fill="${INK}">${escapeXml(targets)}</text>`;
  }).join("");

  return `<g font-family="Aptos, Segoe UI, Arial, sans-serif">
    ${panels.join("")}
    <rect x="92" y="1116" width="1016" height="78" rx="16" fill="#ffffff" stroke="${LINE}" stroke-width="2"/>
    ${targetRows}
  </g>`;
}

function renderLegend(patterns) {
  const startX = patterns.length === 1 ? 360 : 180;
  const itemWidth = patterns.length === 1 ? 480 : 360;
  const items = patterns.map((pattern, index) => {
    const x = startX + index * itemWidth;
    return `<circle cx="${x + 42}" cy="1050" r="16" fill="${pattern.color}"/>
      <text x="${x + 72}" y="1061" font-size="27" font-weight="900" fill="${INK}">${escapeXml(pattern.label)}</text>`;
  }).join("");

  return `<g font-family="Aptos, Segoe UI, Arial, sans-serif">
    <rect x="180" y="1012" width="840" height="76" rx="14" fill="#ffffff" stroke="${LINE}" stroke-width="2"/>
    ${items}
  </g>`;
}

function renderInfoPanel(x, y, width, height, title, lines) {
  let cursor = y + 70;
  const content = lines.slice(0, 4).map((line, index) => {
    const wrapped = wrapLine(line, width > 300 ? 42 : 24);
    const block = wrapped.map((part, subIndex) => {
      const yy = cursor + subIndex * 25;
      return `<text x="${x + 18}" y="${yy}" font-size="${subIndex ? 20 : 22}" font-weight="${subIndex ? 700 : 850}" fill="${subIndex ? MUTED : INK}">${escapeXml(part)}</text>`;
    }).join("");
    cursor += wrapped.length > 1 ? 54 : 34;
    return block;
  }).join("");

  return `<g>
    <rect x="${x}" y="${y}" width="${width}" height="${height}" rx="16" fill="#ffffff" stroke="${LINE}" stroke-width="2"/>
    <text x="${x + 18}" y="${y + 34}" font-size="21" font-weight="900" fill="${GOLD}">${escapeXml(title)}</text>
    ${content}
  </g>`;
}

function computeRiderTargets(origin, directions) {
  const targets = [];
  for (const [df, dr] of directions) {
    let file = origin.file + df;
    let rank = origin.rank + dr;
    while (isInside(file, rank)) {
      targets.push(toSquare(file, rank));
      file += df;
      rank += dr;
    }
  }
  return sortSquares(targets);
}

function computeLeaperTargets(origin, deltas) {
  return deltas
    .map(([df, dr]) => ({ file: origin.file + df, rank: origin.rank + dr }))
    .filter(({ file, rank }) => isInside(file, rank))
    .map(({ file, rank }) => toSquare(file, rank))
    .sort(compareSquare);
}

function computeRayEnds(originSquare, directions) {
  const origin = squareToBoardPoint(originSquare);
  return directions.map(([df, dr]) => {
    let file = origin.file;
    let rank = origin.rank;
    while (isInside(file + df, rank + dr)) {
      file += df;
      rank += dr;
    }
    return toSquare(file, rank);
  });
}

function squareToBoardPoint(square) {
  const match = /^([a-h])([1-8])$/.exec(square);
  if (!match) {
    throw new Error(`Invalid square: ${square}`);
  }
  return {
    file: BOARD_FILES.indexOf(match[1]),
    rank: Number(match[2])
  };
}

function squareCenter(square) {
  const point = squareToBoardPoint(square);
  const size = CARD.boardSize / 8;
  return {
    x: CARD.boardX + point.file * size + size / 2,
    y: CARD.boardY + (8 - point.rank) * size + size / 2
  };
}

function toSquare(file, rank) {
  return `${BOARD_FILES[file]}${rank}`;
}

function isInside(file, rank) {
  return file >= 0 && file < 8 && rank >= 1 && rank <= 8;
}

function sortSquares(squares) {
  return [...squares].sort(compareSquare);
}

function compareSquare(a, b) {
  const af = BOARD_FILES.indexOf(a[0]);
  const bf = BOARD_FILES.indexOf(b[0]);
  const ar = Number(a[1]);
  const br = Number(b[1]);
  return af === bf ? ar - br : af - bf;
}

function patternName(pattern) {
  if (pattern.key) return pattern.key;
  if (pattern.label.includes("rook")) return "rookRider";
  if (pattern.label.includes("knight")) return "knightLeap";
  return pattern.label.toLowerCase().replace(/[^a-z0-9]+/g, "-");
}

function wrapLine(line, max) {
  const words = line.split(/\s+/);
  const rows = [];
  let current = "";

  for (const word of words) {
    const next = current ? `${current} ${word}` : word;
    if (next.length > max && current) {
      rows.push(current);
      current = word;
    } else {
      current = next;
    }
  }

  if (current) rows.push(current);
  return rows.slice(0, 2);
}

function escapeXml(value) {
  return String(value)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}
