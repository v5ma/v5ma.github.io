// Build the Theology Wiki for Cloudflare Pages (wiki.onlyonedevil.com). Claude, 2026-09-25.
// Usage (from the repo root): node scripts/cloudflare-theology-build.mjs [outDir=cf-build]
// Writes <outDir>/public (the site: index.html, 404.html, agent-wiki-theology-route.html, theology-wiki/,
// theology-sources/) and <outDir>/functions. Cloudflare Pages rejects files over 25 MiB (GitHub allowed 100 MB),
// so any larger file is stored as <file>.part-N pieces and a generated Pages Function serves the original URL by
// streaming the pieces back together: the same bytes, the same address, and no wiki content changes.
// Deploy: cd <outDir> && npx wrangler pages deploy public --project-name theology-wiki --branch main
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';

const root = process.cwd();
const out = path.resolve(process.argv[2] || 'cf-build');
const SITE = ['index.html', '404.html', 'agent-wiki-theology-route.html', 'theology-wiki', 'theology-sources'];
const LIMIT = 24 * 1024 * 1024;           // stay below Pages' 25 MiB per-file limit
const PART = 20 * 1024 * 1024;
const TYPES = { '.json': 'application/json; charset=utf-8', '.csv': 'text/csv; charset=utf-8', '.txt': 'text/plain; charset=utf-8' };
if (fs.existsSync(out)) fs.rmSync(out, { recursive: true });
const pub = path.join(out, 'public');
const fnDir = path.join(out, 'functions');
const walk = (p) => (fs.statSync(p).isDirectory() ? fs.readdirSync(p).flatMap((n) => walk(path.join(p, n))) : [p]);
const splits = [];
let files = 0;
for (const entry of SITE) {
  const src = path.join(root, entry);
  if (!fs.existsSync(src)) throw new Error('missing ' + entry);
  for (const file of walk(src)) {
    const rel = path.relative(root, file).split(path.sep).join('/');
    const bytes = fs.readFileSync(file);
    const target = path.join(pub, rel);
    fs.mkdirSync(path.dirname(target), { recursive: true });
    if (bytes.length <= LIMIT) { fs.writeFileSync(target, bytes); files += 1; continue; }
    const parts = [];
    for (let offset = 0, n = 1; offset < bytes.length; offset += PART, n += 1) {
      const name = path.basename(rel) + '.part-' + n;
      fs.writeFileSync(path.join(path.dirname(target), name), bytes.subarray(offset, offset + PART));
      parts.push(name);
      files += 1;
    }
    splits.push({ path: '/' + rel, bytes: bytes.length, sha256: crypto.createHash('sha256').update(bytes).digest('hex'), parts,
      type: TYPES[path.extname(rel).toLowerCase()] || 'application/octet-stream' });
  }
}
for (const s of splits) {
  const fnFile = path.join(fnDir, ...s.path.split('/').filter(Boolean)) + '.js';
  fs.mkdirSync(path.dirname(fnFile), { recursive: true });
  fs.writeFileSync(fnFile, `// Generated by scripts/cloudflare-theology-build.mjs: serves ${s.path} (${s.bytes} bytes,
// SHA-256 ${s.sha256}) by streaming its ${s.parts.length} stored parts in order.
const PARTS = ${JSON.stringify(s.parts)};
const BYTES = ${s.bytes};
export async function onRequest({ request, env }) {
  if (request.method !== 'GET' && request.method !== 'HEAD') {
    return new Response('Method not allowed', { status: 405, headers: { Allow: 'GET, HEAD' } });
  }
  const headers = { 'Content-Type': ${JSON.stringify(s.type)}, 'Content-Length': String(BYTES), 'Cache-Control': 'public, max-age=3600' };
  if (request.method === 'HEAD') return new Response(null, { headers });
  const url = new URL(request.url);
  const dir = url.pathname.slice(0, url.pathname.lastIndexOf('/') + 1);
  const { readable, writable } = new FixedLengthStream(BYTES);
  (async () => {
    try {
      for (const part of PARTS) {
        const res = await env.ASSETS.fetch(new URL(dir + part, url.origin));
        if (!res.ok || !res.body) throw new Error('missing part ' + part);
        await res.body.pipeTo(writable, { preventClose: true });
      }
      await writable.close();
    } catch (error) {
      await writable.abort(error);
    }
  })();
  return new Response(readable, { headers });
}
`);
}
fs.writeFileSync(path.join(out, 'split-files.json'), JSON.stringify(splits, null, 1) + '\n');
console.log(JSON.stringify({ out, files, splits: splits.map((s) => ({ path: s.path, bytes: s.bytes, parts: s.parts.length })) }));
