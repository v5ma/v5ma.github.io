/**
 * Learning to Feel: bounded, deterministic experimental-design check.
 * Synthetic fixtures only. No recordings, training, network calls, or data discovery.
 * Run: node phase-learning-design-check.mjs
 * JSON is written to stdout; this program does not write files.
 */
import assert from 'node:assert/strict';

const TOL = 1e-10;
const basis = [[1, 0], [0, 1], [-1, 0], [0, -1]];
const norm = v => Math.hypot(...v);
const sigmoid = x => 1 / (1 + Math.exp(-x));
const logit = p => {
  assert.ok(p > 0 && p < 1, 'A finite logit requires 0 < p < 1.');
  return Math.log(p / (1 - p));
};
const curve = (a, b, c) => basis.map(([x, y]) => a + b*x + c*y);
const moments = values => {
  assert.equal(values.length, 4);
  values.forEach(x => assert.ok(Number.isFinite(x)));
  return {
    a: values.reduce((s,x) => s+x, 0) / 4,
    b: (values[0] - values[2]) / 2,
    c: (values[1] - values[3]) / 2,
    oppositePairLackOfFit: (values[0]+values[2])-(values[1]+values[3]),
  };
};
const compare = (pre, post) => {
  const x = moments(pre), y = moments(post);
  const v = [x.b, x.c], w = [y.b, y.c];
  const delta = [w[0]-v[0], w[1]-v[1]];
  const determinant = v[0]*w[1] - v[1]*w[0];
  const squaredBaseline = v[0]*v[0] + v[1]*v[1];
  let positiveGainFit;
  if (squaredBaseline <= TOL*TOL) {
    positiveGainFit = {status:'baseline_phase_vector_zero_or_below_numerical_tolerance'};
  } else {
    const gain = Math.max(0, (v[0]*w[0]+v[1]*w[1])/squaredBaseline);
    positiveGainFit = {
      status:'identified_in_this_noiseless_fixture',
      nonnegativeGain:gain,
      residualNorm:norm([w[0]-gain*v[0],w[1]-gain*v[1]]),
    };
  }
  return {
    pre:x, post:y,
    learningInteraction:delta,
    interactionNorm:norm(delta),
    orientationDeterminant:determinant,
    nonnegativeGainFit:positiveGainFit,
  };
};
const near = (x,y) => assert.ok(Math.abs(x-y) < TOL, String(x)+' differs from '+String(y));
const small = x => assert.ok(Math.abs(x) < TOL, 'Expected zero: '+String(x));
const checks = [];
const check = (name,fn) => { fn(); checks.push({name,status:'pass'}); };

const fixtures = {
  meanOnly:compare(curve(2,1,0.5), curve(5,1,0.5)),
  uniformPositiveGain:compare(curve(2,1,0.5),curve(5,2,1)),
  quarterCycleRetuning:compare(curve(2,1,0),curve(2,0,1)),
  gainAndRetuning:compare(curve(2,1,0),curve(5,0,2)),
  initiallyUntuned:compare(curve(2,0,0),curve(2,1,0)),
  halfCycleFlip:compare(curve(2,1,0),curve(2,-1,0)),
};
const probabilityPre=curve(-3,1.2,0.4).map(sigmoid);
const probabilityPost=curve(-1,1.2,0.4).map(sigmoid);
fixtures.rawProbabilityInterceptChange=compare(probabilityPre,probabilityPost);
fixtures.correctLogitInterceptChange=compare(probabilityPre.map(logit),probabilityPost.map(logit));

const harmonicBase=curve(2,1,0.5);
const withSecondHarmonic=harmonicBase.map((x,i)=>x+0.3*[1,-1,1,-1][i]);
fixtures.secondHarmonic=moments(withSecondHarmonic);
const thirdHarmonicAtQuadrature=[0,-1,0,1];
const negativeFundamentalAtQuadrature=curve(0,0,-1);
fixtures.thirdHarmonicAlias={
  sampledValues:thirdHarmonicAtQuadrature,
  indistinguishableFundamental:negativeFundamentalAtQuadrature,
  fitted:moments(thirdHarmonicAtQuadrature),
};
fixtures.referenceDrift={
  apparentRetuning:compare(curve(2,1,0),curve(2,0,1)),
  explanation:'These same samples can be generated by a fixed native tuning curve and a quarter-cycle shift in the measurement reference; samples alone cannot distinguish the two.',
};

check('Quadrature identifies the declared first harmonic',()=>{
  const m=moments(curve(2,1,0.5)); near(m.a,2); near(m.b,1); near(m.c,0.5);
});
check('An additive mean shift has no phase interaction',()=>small(fixtures.meanOnly.interactionNorm));
check('Uniform gain creates a learning-by-phase interaction',()=>assert.ok(fixtures.uniformPositiveGain.interactionNorm>1));
check('Uniform gain has zero orientation determinant and zero gain residual',()=>{
  small(fixtures.uniformPositiveGain.orientationDeterminant);
  small(fixtures.uniformPositiveGain.nonnegativeGainFit.residualNorm);
  near(fixtures.uniformPositiveGain.nonnegativeGainFit.nonnegativeGain,2);
});
check('Equal-amplitude retuning need not raise average response',()=>{
  near(fixtures.quarterCycleRetuning.pre.a,fixtures.quarterCycleRetuning.post.a);
  near(norm([fixtures.quarterCycleRetuning.pre.b,fixtures.quarterCycleRetuning.pre.c]),
       norm([fixtures.quarterCycleRetuning.post.b,fixtures.quarterCycleRetuning.post.c]));
  near(fixtures.quarterCycleRetuning.orientationDeterminant,1);
});
check('The nonnegative-gain fit rejects the quarter-cycle fixture',()=>near(fixtures.quarterCycleRetuning.nonnegativeGainFit.residualNorm,1));
check('Gain plus retuning is not pure gain',()=>assert.ok(fixtures.gainAndRetuning.nonnegativeGainFit.residualNorm>1));
check('A zero baseline makes the orientation comparison unidentified',()=>{
  assert.equal(fixtures.initiallyUntuned.nonnegativeGainFit.status,'baseline_phase_vector_zero_or_below_numerical_tolerance');
});
check('A half-cycle reversal defeats the determinant alone but not the gain-ray check',()=>{
  small(fixtures.halfCycleFlip.orientationDeterminant);
  near(fixtures.halfCycleFlip.nonnegativeGainFit.residualNorm,1);
});
check('Raw binary probabilities can falsely suggest retuning when only latent intercept changes',()=>{
  assert.ok(Math.abs(fixtures.rawProbabilityInterceptChange.orientationDeterminant)>1e-5);
  assert.ok(fixtures.rawProbabilityInterceptChange.nonnegativeGainFit.residualNorm>1e-5);
});
check('The correct logit scale removes that constructed artifact',()=>{
  small(fixtures.correctLogitInterceptChange.interactionNorm);
  small(fixtures.correctLogitInterceptChange.nonnegativeGainFit.residualNorm);
});
check('Opposite-pair residual detects this second harmonic',()=>near(fixtures.secondHarmonic.oppositePairLackOfFit,1.2));
check('Four phase samples cannot distinguish a third-harmonic alias',()=>{
  assert.deepEqual(thirdHarmonicAtQuadrature,negativeFundamentalAtQuadrature);
  small(fixtures.thirdHarmonicAlias.fitted.oppositePairLackOfFit);
});
check('Reference drift is observationally identical in this construction',()=>{
  assert.deepEqual(fixtures.referenceDrift.apparentRetuning,fixtures.quarterCycleRetuning);
});

const result={
  artifact:'Learning to Feel / phase-learning experimental-design check',
  version:1,
  evidenceType:'deterministic synthetic fixtures; not biological or behavioral data',
  scope:'Conditional algebra, counterexamples, and numerical implementation checks only.',
  phaseSamplesRadians:['0','pi/2','pi','3pi/2'],
  claimsNotTested:['SAN biological validity','a new conscious sense','subjective experience','an optimal stimulation protocol','statistical power','originality of the mathematics'],
  totalChecks:checks.length,
  passedChecks:checks.filter(x=>x.status==='pass').length,
  checks,fixtures,
};
process.stdout.write(JSON.stringify(result,null,2)+'\n');

